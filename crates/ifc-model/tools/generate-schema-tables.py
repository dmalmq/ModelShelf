#!/usr/bin/env python3
"""Generate `src/schema_tables.rs` from official IFC EXPRESS schemas.

The reader needs to resolve IFC attribute names to STEP attribute positions. Guessing
positions produces wrong findings, so the positions come from the schema itself: for each
entity we record its supertype and its own explicit attributes in declaration order.
Instance attribute order is then supertype-first, which is exactly ISO 10303-21 ordering.

INVERSE / DERIVE / WHERE / UNIQUE members are excluded: they are not serialised.

Usage:
    python3 tools/generate-schema-tables.py IFC2X3=path/to/IFC2X3_TC1.exp IFC4=path/to/IFC4.exp
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ENTITY_RE = re.compile(r"^ENTITY\s+(\w+)\s*;?\s*$", re.M)
STOP_SECTIONS = ("WHERE", "INVERSE", "DERIVE", "UNIQUE")


def parse_schema(text: str) -> dict[str, tuple[str | None, list[str]]]:
    entities: dict[str, tuple[str | None, list[str]]] = {}
    # Split on ENTITY ... END_ENTITY blocks.
    for block in re.finditer(r"^ENTITY\s+(\w+)(.*?)^END_ENTITY\s*;", text, re.M | re.S):
        name = block.group(1)
        body = block.group(2)
        # Strip the SUPERTYPE OF (...) clause, then read SUBTYPE OF (Parent).
        supertype = None
        subtype = re.search(r"SUBTYPE\s+OF\s*\(\s*(\w+)", body, re.S)
        if subtype:
            supertype = subtype.group(1)
        # Attribute region: after the header (first ';' that closes the declaration) up to
        # the first WHERE/INVERSE/DERIVE/UNIQUE keyword.
        header_end = find_header_end(body)
        region = body[header_end:]
        cut = len(region)
        for keyword in STOP_SECTIONS:
            match = re.search(rf"^\s*{keyword}\s*$", region, re.M)
            if match:
                cut = min(cut, match.start())
        region = region[:cut]
        entities[name] = (supertype, parse_attributes(region))
    return entities


def find_header_end(body: str) -> int:
    """Index just past the ';' that terminates the ENTITY declaration header."""
    depth = 0
    for index, char in enumerate(body):
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        elif char == ";" and depth == 0:
            return index + 1
    return 0


def parse_attributes(region: str) -> list[str]:
    attributes: list[str] = []
    # Attribute declarations are `Name : TYPE;` or `A, B : TYPE;`, possibly wrapped.
    for statement in region.split(";"):
        statement = statement.strip()
        if not statement or ":" not in statement:
            continue
        names, _, _type = statement.partition(":")
        if "=" in names or "<" in names or ">" in names:
            continue
        parsed = [n.strip() for n in names.split(",")]
        if not all(re.fullmatch(r"\w+", n or "") for n in parsed):
            continue
        attributes.extend(parsed)
    return attributes


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    sections: list[str] = []
    for argument in sys.argv[1:]:
        label, _, path = argument.partition("=")
        text = Path(path).read_text(encoding="utf-8", errors="replace")
        entities = parse_schema(text)
        if not entities:
            raise SystemExit(f"no entities parsed from {path}")
        lines = [f"#{label}"]
        for name in sorted(entities):
            supertype, attributes = entities[name]
            lines.append(
                "{}|{}|{}".format(
                    name.upper(),
                    (supertype or "").upper(),
                    ",".join(attributes),
                )
            )
        sections.append("\n".join(lines))
        print(f"{label}: {len(entities)} entities", file=sys.stderr)

    out = Path(__file__).resolve().parents[1] / "src" / "schema_tables.rs"
    body = "\n".join(sections)
    out.write_text(
        "//! Generated by `tools/generate-schema-tables.py` from the official IFC EXPRESS\n"
        "//! schemas (buildingSMART IFC2X3 TC1 and IFC4 ADD2 TC1, via the stepcode data set).\n"
        "//! Do not edit by hand; rerun the generator instead.\n"
        "//!\n"
        "//! Format: sections introduced by `#<SCHEMA>`, then one line per entity:\n"
        "//! `ENTITY|SUPERTYPE|Attr1,Attr2,...` listing that entity's own explicit\n"
        "//! attributes in declaration order. Instance order is supertype attributes first.\n"
        "\n"
        "pub const SCHEMA_TABLES: &str = r#\"" + body + "\"#;\n",
        encoding="utf-8",
    )
    print(f"wrote {out} ({out.stat().st_size} bytes)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
